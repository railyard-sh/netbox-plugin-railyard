class RailyardSyncJob(RailyardJob):
    class Meta:
        name = "Railyard → NetBox sync"

    def run(self, *, project, org=None, dry_run=False, allow_deletes=False, **kwargs):
        cfg = railyard_settings()
        user = self._check_user(
            lambda u: missing_permissions(u.has_perm, dry_run=dry_run, allow_deletes=allow_deletes), "sync"
        )

        # Re-check the target against the allowlist here too: the job is the enforcement point, whatever
        # enqueued it (the form, a shell, a re-run of an older job).
        targets = sync_targets()
        try:
            org = targets.check_org(org)
            project = targets.check_project(project)
        except TargetNotAllowed as exc:
            self._fail(str(exc))

        client = self._client(cfg, org)
        release = netbox_release()
        self.logger.info(
            f"Fetching the NetBox sync document for Railyard project {project!r} (org {org or '(personal)'!r}), "
            f"written for NetBox {release}…"
        )
        try:
            with railyard_sync_logs(self.logger):
                doc = client.netbox_sync_document(project, netbox_version=release)
        except RailyardPlanError as exc:
            self._fail(deliverable_plan_message(exc))
        except (RailyardAPIError, ValueError) as exc:
            self._railyard_failed(exc)

        try:
            source = SyncDocumentAdapter(doc, name="railyard")
            source.load()
        except SyncDocumentError as exc:
            self._fail(str(exc))
        warnings = list(source.warnings)
        if source.document.netbox_version and parse_version(source.document.netbox_version) != parse_version(release):
            warnings.append(
                f"Railyard wrote the document for NetBox {source.document.netbox_version}, not {release}: check the "
                "front port mappings and component types in the dry run."
            )
        try:
            spec = ownership_tag(cfg["url"], source.project_id, source.project_name)
        except ValueError as exc:
            self._fail(str(exc))

        dtl = None
        if cfg["import_components"]:
            dtl = DeviceTypeLibrary(ref=cfg["devicetype_library_ref"], cache_dir=cfg["devicetype_cache_dir"])
        try:
            if dry_run:
                with _rolled_back():
                    return self._dry_run(source, spec, user, cfg, dtl, allow_deletes, warnings)
            with _change_logging(user), transaction.atomic():
                return self._apply(source, spec, user, cfg, dtl, allow_deletes, warnings)
        except (SyncRefused, PermissionDenied, ObjectCrudException, ValidationError, IntegrityError) as exc:
            self.logger.error("Nothing was changed in NetBox: the sync was rolled back.")
            self._fail(str(exc))

    def _target(self, tag, user, cfg, dtl, user_tags) -> NetBoxAdapter:
        return NetBoxAdapter(
            tag=tag,
            user=user,
            user_tags=user_tags,
            import_components=cfg["import_components"],
            devicetype_library=dtl,
            name="netbox",
        )

    @staticmethod
    def _plan(target, source, allow_deletes: bool):
        """Decide what to skip/use as-is/rename, then diff. Read-only."""
        target.load()
        report = target.reconcile(source, allow_deletes=allow_deletes)
        # Creates/updates come from the diff; deletes are handled separately, in dependency order.
        diff = target.diff_from(source, flags=DiffSyncFlags.SKIP_UNMATCHED_DST)
        candidates = target.delete_candidates(source)
        return report, diff, candidates

    def _summary(self, target, diff, deletes) -> dict:
        summary = diff.summary()
        summary["update"] = summary.get("update", 0) + len(target.renames)
        summary["delete"] = len(deletes)
        self.logger.info(f"Diff: {summary}")
        return summary

    def _dry_run(self, source, spec, user, cfg, dtl, allow_deletes, warnings):
        tag = find_ownership_tag(spec)
        if tag is None:
            self.logger.info(
                f"Ownership tag {spec.name!r} doesn't exist yet: this sync owns nothing in NetBox, so nothing "
                "can be updated or deleted."
            )
            self.logger.info(
                "Upgrading from plugin 0.1 (which tagged objects 'RY:<project name>')? Edit that tag before "
                f"syncing so it becomes this project's: slug {spec.slug!r}, name {spec.name!r}, "
                f"description {spec.description!r}."
            )
        user_tags = ensure_user_tags(source, spec, user, dry_run=True, warnings=warnings)
        target = self._target(tag, user, cfg, dtl, user_tags)
        report, diff, candidates = self._plan(target, source, allow_deletes)
        deletes = candidates if allow_deletes else []
        summary = self._summary(target, diff, deletes)
        self._log_report(report, adopt_verb="Would adopt")
        self._log_changes(target, diff, deletes, "Would apply")
        scheduled = {(_label(m), m.nb_id) for m in deletes}
        self._log_deletes(deletes, "Would delete", lambda m: target.preview_delete(m, scheduled))
        self._log_stale(candidates, allow_deletes)
        self._log_list("Warnings", warnings + report.warnings, level="warning")
        self.logger.warning("Dry run — nothing was written to NetBox.")
        return self._result(True, summary, report, spec.name, warnings)

    def _apply(self, source, spec, user, cfg, dtl, allow_deletes, warnings):
        ensure_custom_field(user)
        tag = ensure_ownership_tag(spec, user)
        self.logger.info(f"Railyard-owned objects carry the tag {tag.name!r} (slug {tag.slug!r}).")
        user_tags = ensure_user_tags(source, spec, user, dry_run=False, warnings=warnings)

        target = self._target(tag, user, cfg, dtl, user_tags)
        report, diff, candidates = self._plan(target, source, allow_deletes)
        deletes = candidates if allow_deletes else []
        summary = self._summary(target, diff, deletes)
        self._log_changes(target, diff, deletes, "Applying")
        self._log_deletes(deletes, "Deleting", None)

        # Renames first (the diff is keyed by the new names); then cables, so a re-patched port is free before
        # its new cable is created; then creates and updates; then everything else, dependents first.
        target.apply_renames()
        for model in deletes:
            if model.get_type() == "cable":
                model.delete()
        target.sync_from(source, flags=DiffSyncFlags.SKIP_UNMATCHED_DST, diff=diff)
        for model in deletes:
            if model.get_type() != "cable":
                model.delete()

        self._log_report(report, adopt_verb="Adopted")
        self._log_stale(candidates, allow_deletes)
        self._log_list("Warnings", warnings + report.warnings, level="warning")
        self.logger.info(f"Sync complete: {summary}")
        return self._result(False, summary, report, tag.name, warnings)

    @staticmethod
    def _result(dry_run, summary, report, tag_name, warnings):
        return {
            "dry_run": dry_run,
            "diff": summary,
            "tag": tag_name,
            "referenced": len(report.referenced),
            "conflicts": len(report.conflicts),
            "dependents_skipped": report.dependents_skipped,
            "adopted": len(report.adopted),
            "renamed": len(report.renamed),
            "kept": len(report.kept),
            "warnings": len(warnings) + len(report.warnings),
        }

    def _log_report(self, report, *, adopt_verb: str) -> None:
        self._log_list("Not managed by this sync — used as they are", report.referenced)
        self._log_list("Skipped — would touch objects this sync doesn't own", report.conflicts, level="warning")
        if report.dependents_skipped:
            self.logger.warning(f"Also skipped {report.dependents_skipped} components/cables of skipped objects.")
        self._log_list(f"{adopt_verb} — existing components of devices this sync owns", report.adopted)
        self._log_list("Renamed in Railyard — renamed in place", report.renamed)
        self._log_list("Kept — not deleted, because NetBox would delete or change more", report.kept, level="warning")

    def _log_stale(self, candidates, allow_deletes: bool) -> None:
        if allow_deletes or not candidates:
            return
        self._log_list(
            "Stale — owned objects no longer in Railyard, kept (tick Allow deletes to remove them)",
            [f"{m.get_type()} [{m.get_unique_id()}]" for m in candidates],
        )

    def _log_deletes(self, deletes, verb: str, why_kept) -> None:
        if not deletes:
            return
        self.logger.info(f"{verb} ({len(deletes)}) objects this sync created that are no longer in Railyard:")
        for model in deletes:  # never capped: every delete is named before it happens
            line = f"  · delete: {model.get_type()} [{model.get_unique_id()}]"
            reasons = why_kept(model) if why_kept else []
            if reasons:
                line += f" — would be kept: {'; '.join(reasons)}"
            self.logger.info(line)

    def _log_changes(self, target, diff, deletes, verb: str) -> None:
        """Per-object create/update so a run reads as a changelog, not just a count. Creates on a first sync can
        number in the thousands, so creates and updates are capped; deletes are logged in full elsewhere."""
        planned = planned_changes(diff, len(target.renames), deletes)
        lines = [f"rename: device {old} → {new}" for old, new, _ in target.renames] + change_lines(diff)
        for action in ("create", "update"):
            rows = [
                line
                for line in lines
                if line.startswith(f"{action}: ") or (action == "update" and line.startswith("rename: "))
            ]
            if not rows:
                continue
            by_type = ", ".join(f"{n} {t}" for t, n in sorted(planned[action].items()))
            self.logger.info(f"{verb} — {action} ({len(rows)}): {by_type}")
            for row in rows[: self._LOG_CAP]:
                self.logger.info(f"  · {row}")
            if len(rows) > self._LOG_CAP:
                self.logger.info(f"  · … and {len(rows) - self._LOG_CAP} more {action}s")

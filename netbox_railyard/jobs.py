TAG_COLOUR = "1f8bff"


class _Rollback(Exception):
    """Raised to roll back a dry run's transaction."""


@contextmanager
def _rolled_back():
    """Run a block in a transaction that is always rolled back (a dry run's backstop against writes)."""
    try:
        with transaction.atomic():
            yield
            raise _Rollback
    except _Rollback:
        pass


def _label(model) -> str:
    return _NB_MODEL[model.get_type()]._meta.label_lower


def _change_logging(user):
    """NetBox's request processors (change logging, event rules) for a job running as ``user``."""
    request = NetBoxFakeRequest(
        {
            "META": {},
            "COOKIES": {},
            "POST": {},
            "GET": {},
            "FILES": {},
            "user": user,
            "method": "POST",
            "path": "",
            "id": uuid.uuid4(),
        }
    )
    return apply_request_processors(request)


def netbox_release() -> str:
    """This NetBox's release line (``"4.6"``): the version Railyard writes the sync document for."""
    major, minor = parse_version(settings.RELEASE.version)
    return f"{major}.{minor}"


class _ToJobLog(logging.Handler):
    """Forwards railyard-sync's progress (INFO and up) into a job's log while the job runs."""

    def __init__(self, logger: logging.Logger) -> None:
        super().__init__(logging.INFO)
        self.target = logger

    def emit(self, record: logging.LogRecord) -> None:
        try:
            self.target.log(record.levelno, record.getMessage())
        except Exception:  # pragma: no cover - logging must never break the job
            self.handleError(record)


@contextmanager
def railyard_sync_logs(logger: logging.Logger):
    """Show what railyard-sync logs (its progress lines and warnings; never a token or a body) in the job log."""
    library = logging.getLogger("railyard_sync")
    handler, level = _ToJobLog(logger), library.level
    library.addHandler(handler)
    if library.getEffectiveLevel() > logging.INFO:
        library.setLevel(logging.INFO)
    try:
        yield
    finally:
        library.removeHandler(handler)
        library.setLevel(level)


class SyncRefused(Exception):
    """The sync can't safely continue; the message says why (shown in the job log)."""


class RailyardJob(JobRunner):
    """What both Railyard jobs share: failing with a message, the cap on long lists, and the Railyard client."""

    #: Lists in the job log (creates, updates, references…) show at most this many lines; deletes are never capped.
    _LOG_CAP = 250

    def _fail(self, message: str):
        self.logger.error(message)
        raise JobFailed(message)

    def _check_user(self, missing_for, what: str):
        """The job acts as the user who queued it, and re-checks their permissions now: they may have changed
        since it was queued, and a job can be queued by other means than the form."""
        user = self.job.user
        if user is None or not user.is_active:
            self._fail(f"A Railyard {what} must be queued by an active NetBox user.")
        if missing := missing_for(user):
            self._fail(f"{user} lacks the NetBox permissions this {what} needs: {', '.join(missing)}")
        return user

    def _client(self, cfg: dict, org: str | None) -> RailyardClient:
        try:
            token = railyard_token()
        except ValueError as exc:
            self._fail(str(exc))
        if not token:
            self._fail("Set 'railyard_token' or 'railyard_token_file' in PLUGINS_CONFIG['netbox_railyard'] first.")
        if insecure_url(cfg["url"]):
            self.logger.warning(
                f"railyard_url {cfg['url']!r} is not https: the Railyard token is sent in clear text. Use https."
            )
        try:
            return RailyardClient(cfg["url"], token, org=org)
        except ValueError as exc:
            self._fail(str(exc))

    def _railyard_failed(self, exc: Exception):
        """Fail with what Railyard (or the client) said, with what to do about a token that stopped working."""
        if isinstance(exc, RailyardTokenRejectedError):
            self._fail(f"{exc}\n  Ask a NetBox administrator to rotate the token.")
        self._fail(str(exc))

    def _log_list(self, heading: str, rows: list[str], *, level: str = "info") -> None:
        if not rows:
            return
        log = getattr(self.logger, level)
        log(f"{heading} ({len(rows)}):")
        for row in rows[: self._LOG_CAP]:
            log(f"  · {row}")
        if len(rows) > self._LOG_CAP:
            log(f"  · … and {len(rows) - self._LOG_CAP} more")



"""``RailyardSyncJob`` — the NetBox background Job that syncs a Railyard estate into NetBox.

It shows up in NetBox's core Jobs UI (progress, log, result). The source is Railyard's **NetBox sync
document** (``RailyardClient.netbox_sync_document``, the ``netbox-sync`` deliverable, generated by Railyard's
own NetBox export for this NetBox's release) read by railyard-sync's ``SyncDocumentAdapter``; the target is
the scoped NetBox state (``target.NetBoxAdapter``). They are reconciled with DiffSync — create/update only by
default (``SKIP_UNMATCHED_DST``), plus guarded deletes when ``allow_deletes`` is set.

On hosted Railyard the sync document is a paid deliverable: a plan without deliverables (or an estate past the
plan's deliverable rack limit) is refused with HTTP 402, and the job fails with the upgrade message. A
self-hosted Railyard with billing off allows it.

A dry run is read-only: it never creates the ownership tag, the custom field or design tags, and runs inside
a transaction that is always rolled back as a backstop. A real run applies everything in one transaction
(all or nothing) with NetBox's request processors active, so every change is recorded in the changelog
against the user who queued the job and event rules fire only once it has committed.
"""

